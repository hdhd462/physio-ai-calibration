def fit_platt(p, y):
    p = np.clip(p, 1e-9, 1 - 1e-9)
    lr = LogisticRegression(C=1e6, solver='lbfgs', max_iter=2000)
    lr.fit(logit(p).reshape(-1, 1), y)
    a, b = float(lr.coef_[0, 0]), float(lr.intercept_[0])
    return lambda q: expit(a * logit(np.clip(q, 1e-9, 1 - 1e-9)) + b)


def youden(y, p):
    fpr, tpr, thr = roc_curve(y, p)
    return float(thr[np.argmax(tpr - fpr)])


def decision(y, p, t):
    pred = p >= t
    tp = int(np.sum(pred & (y == 1)))
    fp = int(np.sum(pred & (y == 0)))
    fn = int(np.sum((~pred) & (y == 1)))
    tn = int(np.sum((~pred) & (y == 0)))
    n = len(y)
    nb = tp / n - fp / n * (t / (1 - t))
    return dict(t=float(t), flagged=float(pred.mean()), sens=tp / (tp + fn),
                spec=tn / (tn + fp), nb=float(nb), tp1000=1000 * tp / n, fp1000=1000 * fp / n)


